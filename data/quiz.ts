/** 按类型筛选题目 */
export function getQuestionsByType(type: QuizType): QuizQuestion[] {
  return quizQuestions.filter((q) => q.type === type);
}

/** 随机抽取指定数量的题目 */
export function getRandomQuestions(count: number, type?: QuizType): QuizQuestion[] {
  const pool = type ? getQuestionsByType(type) : quizQuestions;
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}

